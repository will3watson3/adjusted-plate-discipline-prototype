source("season_precision_v3.R")
setDTthreads(2);set.seed(42)
f<-data.table(x=rnorm(200),y=rbinom(200,1,.5))
fit<-gam(y~x,data=f,family=binomial(),method="REML")
ids<-c(1,2);batter<-rep(ids,each=100);weight<-rnorm(200)
p<-sv_gam_precision(fit,f,weight,batter,ids,c(100,100))
X<-predict(fit,f,type="lpmatrix");V<-if(!is.null(fit$Vc)) fit$Vc else fit$Vp
g<-rowsum(X*weight,batter)
expected<-sqrt(rowSums((g%*%V)*g))
stopifnot(max(abs(expected-p$shared))<1e-12,
  max(abs(p$eta-as.numeric(predict(fit,f,type="link"))))<1e-12)
intercept<-gam(y~1,data=f,family=binomial(),method="REML")
p<-sv_gam_precision(intercept,f,rep(c(1,-1),100),batter,ids,c(100,100))
stopifnot(all(p$shared<1e-12),all(p$point>0))
z<-data.table(catcher=factor(rep(1:5,each=100)),eta=0,y=rbinom(500,1,.5))
fr<-bam(y~offset(eta)+s(catcher,bs="re"),data=z,family=binomial(),method="fREML",discrete=TRUE)
skill<-list(fit=fr,tau=.25)
v<-sv_framing_precision(skill,rep("unknown",20),rep(1,20),rep(1,20),1,20)
V<-if(!is.null(fr$Vc)) fr$Vc else fr$Vp
stopifnot(abs(v-100*sqrt(V[1,1]+.25^2))<1e-10)
v2<-sv_framing_precision(skill,rep(c("unknown1","unknown2"),each=10),rep(1,20),rep(1,20),1,20)
stopifnot(v2<v)
v3<-sv_framing_precision(skill,rep("1",20),rep(c(1,-1),10),rep(1,20),1,20)
stopifnot(v3<1e-12)
se<-vd_cluster_se(c(10,10,10),c(1,2,3))
set.seed(42);boot<-sv_boot_rate(c(10,10,10),c(1,2,3),B=200)
stopifnot(is.finite(se),all(is.finite(boot)),boot["low"]<=boot["high"])
cat("7 shared-gradient/framing/precision checks passed\n")
