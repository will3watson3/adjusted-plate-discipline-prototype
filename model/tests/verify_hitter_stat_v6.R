source('hitter_stat_v6.R')
setDTthreads(2)
checks<-list();check<-function(n,x){if(!isTRUE(x)) stop(n);checks[[length(checks)+1L]]<<-data.table(check=n,passed=TRUE)}
manifest<-readRDS(file.path(H6_MODELS,'manifest.rds'));vd_check_hash(manifest$inputs)
check('frozen inputs unchanged',TRUE)
legacy<-fread('reports/decision_validation/run_input_fingerprints.csv')
legacy<-legacy[grepl('\\.R$|fit_2022_2023\\.rds$',path)]
vd_check_hash(legacy)
check('original scoring models and transformations unchanged',TRUE)
extra<-vd_hash(c(legacy$path,'data/models/decision_validation/league_policy_2022_2023.rds',
  'hitter_stat_v6.R','current_hitter_stat.R','tests/verify_hitter_stat_v6.R'))
vd_check_hash(extra);fwrite(extra,file.path(H6_REPORT,'additional_input_hashes.csv'))
check('selected regional umpire model adopted',manifest$strike_method=='umpire_region_model')
ref<-readRDS(file.path(H6_MODELS,'season_reference_2024.rds'))
check('standardization reference fixed in 2024',ref$year==2024L&&ref$scale>0)
for(year in 2024:2025) {
  checky<-function(n,x) check(paste(year,n),x)
  d<-as.data.table(readRDS(file.path(H6_MODELS,sprintf('decision_values_%d.rds',year))))
  old<-as.data.table(readRDS(sprintf('data/models/catcher_framing_v2/decision_values_%d.rds',year)))
  v5<-as.data.table(readRDS(sprintf('data/models/umpire_v5/decision_comparison_%d.rds',year)))
  checky('exact pitch keys and order',identical(dv_key(d),dv_key(old))&&!anyDuplicated(d,by=CS_KEYS))
  checky('support and unsupported reasons unchanged',identical(d$primary_supported,old$primary_supported)&&identical(d$support_reason,old$support_reason))
  checky('swing and reference frozen',identical(d$q_swing_basic,old$q_swing_basic)&&identical(d$p_swing_reference,old$p_swing_reference))
  checky('selected umpire probability linked',isTRUE(all.equal(d$p_called_strike_if_ordinary_take,v5$p_called_strike,tolerance=1e-12)))
  checky('take value linked',isTRUE(all.equal(d$q_take_basic,v5$q_take,tolerance=1e-12)))
  checky('score matches upstream selected candidate',isTRUE(all.equal(d$score,v5$score,tolerance=1e-12)))
  st<-build_take_state_values(read_re_baseline());k<-match(d$re288_state,st$re288_state)
  finite<-is.finite(d$q_take_basic)&!is.na(k)
  checky('take value bounded by exact branches',all(d$q_take_basic[finite]>=pmin(st$ball_value[k[finite]],st$called_strike_value[k[finite]])-1e-12&d$q_take_basic[finite]<=pmax(st$ball_value[k[finite]],st$called_strike_value[k[finite]])+1e-12))
  checky('gap exact swing minus take',isTRUE(all.equal(d$swing_minus_take,d$q_swing_basic-d$q_take_basic,tolerance=1e-12)))
  s<-d[primary_supported==TRUE]
  checky('new uncertainty finite positive on supported cohort',all(is.finite(s$gap_model_se_bound)&s$gap_model_se_bound>=0&is.finite(s$above_reference_model_se_bound)))
  checky('unsupported uncertainty omitted',all(is.na(d$gap_model_se_bound[!d$primary_supported])))
  checky('RE warnings and extremes excluded',!any(d$primary_supported&(d$re_order_warning|d$extreme_bip_value)))
  checky('fresh uncertainty status',all(d$uncertainty_status=='recomputed_conditional_first_order_sd_sum_bound'))
  h<-fread(file.path(H6_REPORT,sprintf('hitters_%d.csv',year)))
  expected<-s[,.(rate=100*mean(score),n=.N),by=batter];j<-match(expected$batter,h$batter)
  checky('season average uses supported pitches only',max(abs(expected$rate-h$runs_per100[j]))<1e-10&&all(expected$n==h$supported[j]))
  checky('coverage denominators match within CSV rounding',max(abs(h$coverage-h$supported/h$eligible))<1e-12)
  checky('qualified exposure contract',all(h$qualified==(h$supported>=500&h$games>=60&h$coverage>=.7)))
  checky('index uses same frozen reference',max(abs(h$decision_plus[j]-(100+10*(expected$rate-ref$center)/ref$scale)))<1e-9)
  checky('model interval transformed consistently',max(abs(h$decision_plus_model_low[j]-(100+10*(h$model_only_low[j]-ref$center)/ref$scale)))<1e-9)
  sh<-fread(file.path(H6_REPORT,sprintf('uncertainty_components_%d.csv',year)))
  cols<-setdiff(names(sh),c('batter','supported','shared_model_se_bound_per100'))
  checky('model components recombine',max(abs(rowSums(as.matrix(sh[,..cols]))-sh$shared_model_se_bound_per100))<1e-10)
  checky('joint and weekly uncertainty present',all(c('catcher_umpire_joint','weekly_calibration')%in%cols)&&any(sh$weekly_calibration>0))
  point<-s[,.(bound=100*mean(above_reference_model_se_bound)),by=batter]
  checky('aggregate gradient bound does not exceed pointwise bound',all(sh$shared_model_se_bound_per100<=point$bound[match(sh$batter,point$batter)]+1e-8))
  l<-fread(file.path(H6_REPORT,sprintf('weekly_uncertainty_%d.csv',year)))
  checky('weekly evidence strictly earlier',all(as.Date(l$train_end)<as.Date(l$start),na.rm=TRUE)&&all(l$se>=0&is.finite(l$se)))
  bs<-fread(file.path(H6_REPORT,sprintf('sampling_sensitivity_%d.csv',year)))
  checky('serial sampling sensitivity complete',setequal(unique(bs$block_games),c(1,7,14))&&nrow(bs)==3*sum(h$qualified,na.rm=TRUE)&&all(is.finite(bs$se)))
  cmp<-fread(file.path(H6_REPORT,sprintf('comparison_v4_%d.csv',year)))
  checky('v4 change reconstructs',max(abs(cmp[is.finite(v4_runs100)]$runs_per100-cmp[is.finite(v4_runs100)]$v4_runs100-cmp[is.finite(v4_runs100)]$change_runs100))<1e-9)
  if(year==2024L) {
    z<-h[qualified==TRUE];w<-z$supported/sum(z$supported)
    checky('development index weighted mean 100',abs(sum(w*z$decision_plus)-100)<1e-9)
    checky('development index weighted SD 10',abs(sqrt(sum(w*(z$decision_plus-100)^2))-10)<1e-9)
  }
  rm(d,old,v5,s);gc(verbose=FALSE)
}
vd_check_hash(extra)
fwrite(rbindlist(checks),file.path(H6_REPORT,'artifact_verification.csv'))
cat(length(checks),'hitter integration artifact checks passed\n')
